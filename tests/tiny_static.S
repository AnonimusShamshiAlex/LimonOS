/* Настоящий, по-настоящему слинкованный статический x86-64 Linux ELF-бинарь:
 * делает ровно exit(42) через syscall. Нужен только как честная фикстура для
 * tests/elf_host.c — чтобы парсер проверялся на байтах реального ld, а не на
 * байтах, которые мы сами придумали "похожими на ELF". */
.global _start
.text
_start:
    movq $60, %rax      /* sys_exit */
    movq $42, %rdi
    syscall
